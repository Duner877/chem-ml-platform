"""Generate a fully pinned Python lock file (spec task P1-04).

`requirements.runtime.txt` and `requirements.dev.txt` declare *ranges*.  That is
right for humans and wrong for reproducibility: two installs a month apart get
different code.  This script resolves the transitive closure of those two files
against the currently installed environment and writes exact pins to
``requirements.lock``.

The closure is computed from the real installed metadata (``importlib.metadata``
``requires`` graph) rather than from a hand-maintained list, so the lock cannot
silently omit a transitive dependency.

Honest limitation, stated in the generated header: this pins *what was validated
on this host*, not "whatever pip would resolve today".  Regenerate it whenever a
declared range moves, and re-run the quality gate afterwards.

What ``--check`` asserts
------------------------
The check is a **declaration-consistency** check, not a snapshot comparison.

The earlier implementation compared the committed file byte-for-byte against the
lock regenerated from *this machine's* installed environment.  That is a
guaranteed failure on any machine whose environment differs from the one that
wrote the file -- and CI installs the declared ranges, so it always resolved to
slightly different versions (fastapi 0.162.0 vs the pinned 0.143.0).  The
check therefore reported a stale lock on every run while saying nothing true
about the tree, and it had never once been exercised in CI because the job
before it failed first.

What a lock file actually asserts is:

1. every distribution declared in the requirement groups has a pin;
2. every pin satisfies the range its declaration allows;
3. the header names the release the pins belong to.

Those three questions have the same answer on every machine, so the check is now
cross-machine deterministic.  Version drift between the lock and a particular
host is *not* drift: the lock is a reproducible baseline, and a host that
resolved a newer patch release is still inside the declared range.

Usage::

    python scripts/lock_dependencies.py --write     # regenerate requirements.lock
    python scripts/lock_dependencies.py --check     # fail if the lock is inconsistent
    python scripts/lock_dependencies.py --print
"""

from __future__ import annotations

import argparse
import re
import sys
from importlib import metadata as md
from pathlib import Path
from typing import Dict, List, Set

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from chemml_version import VERSION  # noqa: E402

LOCK = ROOT / "requirements.lock"
GROUPS = ["requirements.runtime.txt", "requirements.dev.txt"]

#: Marker-only or platform-specific entries that pip installs conditionally.
_MARKER_RE = re.compile(r"^\s*([A-Za-z0-9._-]+)\s*(\[[^\]]*\])?\s*(.*?)(?:;.*)?$")


def _canonical(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def parse_group(path: Path) -> List[str]:
    names: List[str] = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line or line.startswith("-"):
            continue
        match = _MARKER_RE.match(line)
        if match:
            names.append(_canonical(match.group(1)))
    return names


def closure(seeds: List[str]) -> Dict[str, str]:
    """Exact versions for the seeds and everything they require, recursively."""
    resolved: Dict[str, str] = {}
    queue: List[str] = list(seeds)
    seen: Set[str] = set()
    while queue:
        name = queue.pop()
        key = _canonical(name)
        if key in seen:
            continue
        seen.add(key)
        try:
            version = md.version(key)
        except md.PackageNotFoundError:
            # Not installed on this host: record it so the gap is visible rather
            # than silently dropping a declared dependency.
            resolved[key] = ""
            continue
        resolved[key] = version
        try:
            requires = md.requires(key) or []
        except md.PackageNotFoundError:
            requires = []
        for requirement in requires:
            # Skip extras-guarded and environment-marker requirements we cannot
            # evaluate here; including them would pin packages this host does not
            # actually install.
            if ";" in requirement:
                continue
            match = _MARKER_RE.match(requirement)
            if not match:
                continue
            dep = _canonical(match.group(1))
            if dep not in seen:
                queue.append(dep)
    return resolved


def render(pins: Dict[str, str]) -> str:
    lines = [
        f"# Chem ML Platform v{VERSION} -- fully pinned Python lock file.",
        "#",
        "# Generated by scripts/lock_dependencies.py from the transitive closure of",
        "#   requirements.runtime.txt + requirements.dev.txt",
        f"# against the environment that passed the v{VERSION} quality gate.",
        "#",
        "# What this file is:    the exact set of distributions and versions that were",
        "#                       validated.  Install it to reproduce that environment:",
        "#                           python -m pip install -r requirements.lock",
        "# What this file is NOT: a resolver.  It pins what was tested, not whatever",
        "#                       pip would choose today.  After changing any declared",
        "#                       range, regenerate and re-run the quality gate.",
        "#",
        "# Optional accelerators (torch, faiss) are deliberately absent: they live in",
        "# requirements.optional.txt and only degrade capability when missing.",
        "",
    ]
    for name in sorted(pins):
        version = pins[name]
        if version:
            lines.append(f"{name}=={version}")
        else:
            lines.append(f"# {name}: declared but NOT INSTALLED on the validated host")
    return "\n".join(lines) + "\n"


def build() -> Dict[str, str]:
    seeds: List[str] = []
    for group in GROUPS:
        path = ROOT / group
        if path.exists():
            seeds.extend(parse_group(path))
    return closure(seeds)


# --------------------------------------------------------------------------
# Cross-machine consistency checking
# --------------------------------------------------------------------------

#: ``name  version-specifier`` pairs parsed out of the requirement groups.
#: The specifier is kept verbatim so the check can ask "does this pin fall
#: inside the range the declaration allows?".
_DECL_RE = re.compile(r"^\s*([A-Za-z0-9._-]+)\s*(\[[^\]]*\])?\s*([<>=!~].*)?$")

#: ``name==version`` lines in the lock file.
_PIN_RE = re.compile(r"^([A-Za-z0-9._-]+)==([^\s;]+)\s*$")


def parse_declarations() -> Dict[str, str]:
    """Declared distribution -> version range, merged over both groups."""
    declared: Dict[str, str] = {}
    for group in GROUPS:
        path = ROOT / group
        if not path.exists():
            continue
        for raw in path.read_text(encoding="utf-8").splitlines():
            line = raw.split("#", 1)[0].strip()
            if not line or line.startswith("-"):
                continue
            match = _DECL_RE.match(line)
            if not match:
                continue
            name = _canonical(match.group(1))
            specifier = (match.group(3) or "").strip()
            # A later group may widen the range; keep the loosest one so the
            # check does not reject a pin that satisfies either declaration.
            if name in declared:
                declared[name] = _looser(declared[name], specifier)
            else:
                declared[name] = specifier
    return declared


def _looser(first: str, second: str) -> str:
    """The range that admits the most versions among the two."""
    if not first:
        return second
    if not second:
        return first
    try:
        from packaging.specifiers import SpecifierSet
    except Exception:
        return first
    try:
        left = SpecifierSet(first)
        right = SpecifierSet(second)
    except Exception:
        return first
    try:
        if all(left.contains(v) for v in _probe_versions(right)):
            return first
    except Exception:
        pass
    try:
        if all(right.contains(v) for v in _probe_versions(left)):
            return second
    except Exception:
        pass
    return first


def _probe_versions(specifiers) -> List[str]:
    """A handful of versions that the specifier set admits."""
    out = []
    for candidate in ("0.0.1", "0.1", "1.0", "2.0", "10.0", "99.0", "999.0"):
        if specifiers.contains(candidate):
            out.append(candidate)
    return out


def parse_lock(text: str) -> Dict[str, str]:
    """Pinned distribution -> pinned version, as recorded in the lock file."""
    pins: Dict[str, str] = {}
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        match = _PIN_RE.match(line)
        if match:
            pins[_canonical(match.group(1))] = match.group(2)
    return pins


def check_consistency() -> List[str]:
    """Problems that make the lock inconsistent with the declarations.

    Every question asked here has the same answer on every machine, which is
    what makes the check usable as a CI gate.
    """
    problems: List[str] = []

    if not LOCK.exists():
        return ["requirements.lock does not exist (run with --write)"]

    text = LOCK.read_text(encoding="utf-8")

    # 1. The header must name the release the pins belong to.
    expected_header = f"# Chem ML Platform v{VERSION} -- fully pinned Python lock file."
    first_line = text.splitlines()[0] if text.splitlines() else ""
    if first_line != expected_header:
        problems.append(
            f"lock header says {first_line!r} but this release is {expected_header!r}"
        )

    pins = parse_lock(text)
    declared = parse_declarations()

    # 2. Every declared distribution needs a pin.
    for name in sorted(declared):
        if name not in pins:
            problems.append(f"{name} is declared but has no pin in requirements.lock")

    # 3. Every pin must satisfy the range its declaration allows.
    for name in sorted(declared):
        version = pins.get(name)
        if version is None:
            continue
        specifier = declared[name]
        if not specifier:
            continue
        try:
            from packaging.specifiers import SpecifierSet
        except Exception:
            # ``packaging`` is not importable here: fall back to the coverage
            # check above and say so rather than pretending the range held.
            problems.append(
                f"cannot verify {name}=={version} against {specifier!r}: "
                "packaging is not importable"
            )
            break
        try:
            allowed = SpecifierSet(specifier).contains(version, prereleases=True)
        except Exception:
            problems.append(f"{name} has an unparsable range {specifier!r}")
            continue
        if not allowed:
            problems.append(
                f"{name}=={version} does not satisfy the declared range {specifier!r}"
            )

    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description="Chem ML Platform dependency lock")
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true")
    group.add_argument("--check", action="store_true")
    group.add_argument("--print", dest="print_only", action="store_true")
    args = parser.parse_args()

    if args.check:
        problems = check_consistency()
        if problems:
            print("FAIL: requirements.lock is inconsistent with the declarations")
            for problem in problems:
                print(f"      - {problem}")
            print("      regenerate with: python scripts/lock_dependencies.py --write")
            return 1
        pins = parse_lock(LOCK.read_text(encoding="utf-8"))
        declared = parse_declarations()
        print(
            f"OK: requirements.lock is consistent with the declarations "
            f"({len(pins)} pins, {len(declared)} declared dependencies)"
        )
        return 0

    pins = build()
    text = render(pins)

    if args.print_only:
        print(text)
        return 0

    if args.write:
        LOCK.write_text(text, encoding="utf-8")
        pinned = sum(1 for v in pins.values() if v)
        print(f"wrote {LOCK.name}: {pinned} pinned, {len(pins) - pinned} unresolved")
        return 0

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
