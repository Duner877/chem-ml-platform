"""Generate a fully pinned Python lock file (spec task P1-04).

`requirements.runtime.txt` and `requirements.dev.txt` declare *ranges*.  That is
right for humans and wrong for reproducibility: two installs a month apart get
different code.  This script resolves the transitive closure of those two files
against the currently installed environment and writes exact pins to
``requirements.lock``.

The closure is computed from the real installed metadata (``importlib.metadata``
``requires`` graph) rather than from a hand-maintained list, so the lock cannot
silently omit a transitive dependency.

Honest limitation, stated in the generated header: this pins *what was validated
on this host*, not "whatever pip would resolve today".  Regenerate it whenever a
declared range moves, and re-run the quality gate afterwards.

Usage::

    python scripts/lock_dependencies.py --write     # regenerate requirements.lock
    python scripts/lock_dependencies.py --check     # fail if the lock is stale
    python scripts/lock_dependencies.py --print
"""

from __future__ import annotations

import argparse
import re
import sys
from importlib import metadata as md
from pathlib import Path
from typing import Dict, List, Set

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from chemml_version import VERSION  # noqa: E402

LOCK = ROOT / "requirements.lock"
GROUPS = ["requirements.runtime.txt", "requirements.dev.txt"]

#: Marker-only or platform-specific entries that pip installs conditionally.
_MARKER_RE = re.compile(r"^\s*([A-Za-z0-9._-]+)\s*(\[[^\]]*\])?\s*(.*?)(?:;.*)?$")


def _canonical(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def parse_group(path: Path) -> List[str]:
    names: List[str] = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line or line.startswith("-"):
            continue
        match = _MARKER_RE.match(line)
        if match:
            names.append(_canonical(match.group(1)))
    return names


def closure(seeds: List[str]) -> Dict[str, str]:
    """Exact versions for the seeds and everything they require, recursively."""
    resolved: Dict[str, str] = {}
    queue: List[str] = list(seeds)
    seen: Set[str] = set()
    while queue:
        name = queue.pop()
        key = _canonical(name)
        if key in seen:
            continue
        seen.add(key)
        try:
            version = md.version(key)
        except md.PackageNotFoundError:
            # Not installed on this host: record it so the gap is visible rather
            # than silently dropping a declared dependency.
            resolved[key] = ""
            continue
        resolved[key] = version
        try:
            requires = md.requires(key) or []
        except md.PackageNotFoundError:
            requires = []
        for requirement in requires:
            # Skip extras-guarded and environment-marker requirements we cannot
            # evaluate here; including them would pin packages this host does not
            # actually install.
            if ";" in requirement:
                continue
            match = _MARKER_RE.match(requirement)
            if not match:
                continue
            dep = _canonical(match.group(1))
            if dep not in seen:
                queue.append(dep)
    return resolved


def render(pins: Dict[str, str]) -> str:
    lines = [
        f"# Chem ML Platform v{VERSION} -- fully pinned Python lock file.",
        "#",
        "# Generated by scripts/lock_dependencies.py from the transitive closure of",
        "#   requirements.runtime.txt + requirements.dev.txt",
        "# against the environment that passed the v0.7.2 quality gate.",
        "#",
        "# What this file is:    the exact set of distributions and versions that were",
        "#                       validated.  Install it to reproduce that environment:",
        "#                           python -m pip install -r requirements.lock",
        "# What this file is NOT: a resolver.  It pins what was tested, not whatever",
        "#                       pip would choose today.  After changing any declared",
        "#                       range, regenerate and re-run the quality gate.",
        "#",
        "# Optional accelerators (torch, faiss) are deliberately absent: they live in",
        "# requirements.optional.txt and only degrade capability when missing.",
        "",
    ]
    for name in sorted(pins):
        version = pins[name]
        if version:
            lines.append(f"{name}=={version}")
        else:
            lines.append(f"# {name}: declared but NOT INSTALLED on the validated host")
    return "\n".join(lines) + "\n"


def build() -> Dict[str, str]:
    seeds: List[str] = []
    for group in GROUPS:
        path = ROOT / group
        if path.exists():
            seeds.extend(parse_group(path))
    return closure(seeds)


def main() -> int:
    parser = argparse.ArgumentParser(description="Chem ML Platform dependency lock")
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true")
    group.add_argument("--check", action="store_true")
    group.add_argument("--print", dest="print_only", action="store_true")
    args = parser.parse_args()

    pins = build()
    text = render(pins)

    if args.print_only:
        print(text)
        return 0

    if args.write:
        LOCK.write_text(text, encoding="utf-8")
        pinned = sum(1 for v in pins.values() if v)
        print(f"wrote {LOCK.name}: {pinned} pinned, {len(pins) - pinned} unresolved")
        return 0

    if not LOCK.exists():
        print("FAIL: requirements.lock does not exist (run with --write)")
        return 1
    if LOCK.read_text(encoding="utf-8") != text:
        print("FAIL: requirements.lock is stale relative to the installed environment")
        print("      regenerate with: python scripts/lock_dependencies.py --write")
        return 1
    print(f"OK: requirements.lock matches the installed environment ({len(pins)} pins)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
