#!/usr/bin/env python
"""Run the scientific agent from the command line.

The agent is the platform's *scientific workflow controller*: it takes a
natural language question, plans a workflow, executes it and reports the
conclusion -- all offline unless an LLM is configured.

Usage
-----
    python scripts/run_agent.py "请分析这个未知化合物"
    python scripts/run_agent.py -q "设计一个锂离子电池正极材料" --mode cloud
    python scripts/run_agent.py -q "..." --out output/agent_report.md
    python scripts/run_agent.py -q "..." --json

Options
-------
``--mode``    set the AI mode before running (auto / cloud / local / offline)
``--no-llm``  force the deterministic rule planner
``--json``    emit a machine readable result instead of the text report
``--out``     render the report to a file (.md / .html / .pdf)
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Dict, List

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))


def run_agent(
    question: str,
    *,
    language: str = "zh",
    use_llm: bool = True,
    max_nodes: int = 12,
    mode: str = "",
) -> Dict[str, Any]:
    """Execute the agent node once and return its outputs."""
    if mode:
        import ai_runtime

        ai_runtime.set_mode(mode)

    from nodes.agent import run_question

    return run_question(
        question, language=language, use_llm=use_llm, max_nodes=max_nodes
    )


def summary(outputs: Dict[str, Any]) -> Dict[str, Any]:
    """Condense the agent outputs into a JSON serialisable summary."""
    from nodes.agent import summarise

    return summarise(outputs)


def render(outputs: Dict[str, Any], path: str) -> str:
    """Render the agent report to ``path`` (extension picks the format)."""
    from report_agent import build_report

    target = Path(path)
    suffix = target.suffix.lower().lstrip(".") or "markdown"
    fmt = {"md": "markdown", "markdown": "markdown", "html": "html", "pdf": "pdf"}.get(
        suffix, "markdown"
    )
    report = outputs.get("report")
    objects = [item for item in (report, outputs.get("table"), outputs.get("text")) if item]
    result = build_report(
        objects,
        title=getattr(report, "title", "Agent report"),
        summary="Generated by scripts/run_agent.py",
        format=fmt,
        path=str(target),
    )
    return getattr(result, "path", str(target))


def main(argv: List[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("question", nargs="?", default="", help="scientific question (natural language)")
    parser.add_argument("-q", "--question", dest="question_opt", default="", help="question (alternative to the positional)")
    parser.add_argument("--mode", default="", help="AI mode: auto | cloud | local | offline")
    parser.add_argument("--language", default="zh", choices=["zh", "en"], help="report language")
    parser.add_argument("--no-llm", action="store_true", help="use the rule planner only")
    parser.add_argument("--max-nodes", type=int, default=12, help="cap on generated nodes")
    parser.add_argument("--json", action="store_true", help="emit JSON instead of text")
    parser.add_argument("--out", default="", help="render the report to a .md/.html/.pdf file")
    args = parser.parse_args(argv)

    question = (args.question_opt or args.question or "").strip()
    if not question:
        parser.error("a question is required (positional or -q)")

    outputs = run_agent(
        question,
        language=args.language,
        use_llm=not args.no_llm,
        max_nodes=args.max_nodes,
        mode=args.mode,
    )
    data = summary(outputs)

    if args.out:
        data["report_path"] = render(outputs, args.out)

    if args.json:
        print(json.dumps(data, ensure_ascii=False, indent=2, default=str))
        return 0

    print(f"问题      : {data['question']}")
    print(f"识别意图  : {data['intent']}")
    print(f"规划引擎  : {data['engine']}")
    print(f"执行节点  : {', '.join(data['nodes']) or '(none)'}")
    print(f"执行状态  : {data['status']}")
    if data["notes"]:
        print("备注      :")
        for note in data["notes"]:
            print(f"  - {note}")
    print("\n结论\n" + "-" * 60)
    print(data["conclusion"] or "(no narrative)")
    if data.get("report_path"):
        print(f"\n报告已写入: {data['report_path']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
