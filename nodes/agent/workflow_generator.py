"""Workflow generator: plan -> executable workflow JSON.

The generator is deliberately conservative: it only wires ports it can verify
against the live node catalogue.  A step whose output port does not exist is
still added, but the connection is reported in ``warnings`` instead of silently
producing a workflow the engine will reject.

Recipes carry explicit ``inputs`` mappings (``{"target_port": "step.port"}``),
so the emitted graph mirrors a hand verified workflow rather than a naive
linear chain -- which matters because most scientific nodes are fan-in
evidence fusion points, not pipes.
"""

from __future__ import annotations

from typing import Any, Dict, List, Optional

from nodes.agent.planner import Plan

__all__ = ["WorkflowGenerator", "generate_workflow"]


class WorkflowGenerator:
    """Turn a :class:`~nodes.agent.planner.Plan` into a workflow document."""

    def __init__(self, catalog: Optional[Dict[str, Dict[str, Any]]] = None) -> None:
        self.catalog = catalog or {}

    # -- catalogue helpers --------------------------------------------------- #
    def _spec(self, node_type: str) -> Dict[str, Any]:
        return dict(self.catalog.get(node_type) or {})

    def _ports(self, node_type: str, kind: str) -> List[Dict[str, Any]]:
        key = "inputs" if kind == "input" else "outputs"
        return list(self._spec(node_type).get(key) or [])

    def _port_names(self, node_type: str, kind: str) -> List[str]:
        return [str(port.get("name", "")) for port in self._ports(node_type, kind)]

    def _first_port(self, node_type: str, kind: str) -> Optional[str]:
        names = self._port_names(node_type, kind)
        return names[0] if names else None

    def _has_port(self, node_type: str, kind: str, port_name: str) -> bool:
        return port_name in self._port_names(node_type, kind)

    # -- generation ---------------------------------------------------------- #
    def generate(self, plan: Plan, name: str = "", layout: str = "horizontal") -> Dict[str, Any]:
        """Build a workflow document from ``plan``.

        ``layout`` places the nodes either left to right (``horizontal``) or top
        to bottom (``vertical``).
        """
        nodes: List[Dict[str, Any]] = []
        edges: List[Dict[str, Any]] = []
        warnings: List[str] = []
        by_id: Dict[str, str] = {}

        for index, step in enumerate(plan.steps):
            node_id = step.node_id or f"{step.node_type}_{index}"
            by_id[node_id] = step.node_type
            entry: Dict[str, Any] = {
                "id": node_id,
                "type": step.node_type,
                "label": step.node_type,
                "params": dict(step.params or {}),
            }
            if layout == "horizontal":
                entry["position"] = {"x": 80 + index * 220, "y": 80}
            else:
                entry["position"] = {"x": 80, "y": 80 + index * 140}
            nodes.append(entry)

        for step in plan.steps:
            target_id = step.node_id
            for target_port, source in (step.inputs or {}).items():
                edge, warning = self._edge(
                    by_id, target_id, step.node_type, target_port, str(source)
                )
                if edge is not None:
                    edges.append(edge)
                if warning:
                    warnings.append(warning)

        document: Dict[str, Any] = {
            "name": name or f"agent:{plan.intent}",
            "description": plan.question or f"generated by the agent (intent: {plan.intent})",
            "metadata": {
                "generated_by": "ScientificAgentNode",
                "intent": plan.intent,
                "planner": plan.engine,
            },
            "nodes": nodes,
            "edges": edges,
        }
        if warnings:
            document["metadata"]["warnings"] = warnings
        if plan.notes:
            document["metadata"]["notes"] = list(plan.notes)
        return document

    # -- edge construction --------------------------------------------------- #
    def _edge(
        self,
        by_id: Dict[str, str],
        target_id: str,
        target_type: str,
        target_port: str,
        source: str,
    ) -> tuple[Optional[Dict[str, Any]], str]:
        """Resolve one ``"step.port"`` reference into an edge (plus a warning)."""
        step_id, _, port_name = source.partition(".")
        source_type = by_id.get(step_id)
        if source_type is None:
            return None, f"{target_id}.{target_port}: unknown source step {step_id!r}"
        if not port_name:
            port_name = self._first_port(source_type, "output") or ""
        if not port_name:
            return None, f"{target_id}.{target_port}: {source_type} declares no output port"
        if self.catalog and not self._has_port(source_type, "output", port_name):
            return (
                None,
                f"{target_id}.{target_port}: {source_type} has no output port {port_name!r}",
            )
        if self.catalog and not self._has_port(target_type, "input", target_port):
            return (
                None,
                f"{target_id}.{target_port}: {target_type} has no input port {target_port!r}",
            )
        edge = {
            "source": step_id,
            "source_port": port_name,
            "target": target_id,
            "target_port": target_port,
        }
        return edge, ""

    # -- chain helpers ------------------------------------------------------- #
    def fan_in(
        self,
        sources: List[str],
        target_type: str,
        target_port: str = "",
        target_id: str = "",
    ) -> List[Dict[str, Any]]:
        """Edges feeding several sources into one node (evidence fusion)."""
        port = target_port or self._first_port(target_type, "input") or "input"
        node_id = target_id or target_type
        edges: List[Dict[str, Any]] = []
        for source in sources:
            source_port = self._first_port(source, "output")
            edge: Dict[str, Any] = {"source": source, "target": node_id, "target_port": port}
            if source_port:
                edge["source_port"] = source_port
            edges.append(edge)
        return edges


def generate_workflow(
    plan: Plan, catalog: Optional[Dict[str, Dict[str, Any]]] = None, name: str = ""
) -> Dict[str, Any]:
    """Shorthand for :meth:`WorkflowGenerator.generate`."""
    return WorkflowGenerator(catalog).generate(plan, name=name)
