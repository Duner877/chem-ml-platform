"""Bilingual (zh / en) display layer for the node catalogue.

The node classes carry their *canonical* metadata in Chinese prose (that is the
language the scientific reports are written in) while their ``name`` /
``category`` fields are English technical identifiers.  The GUI must be able to
show **either** language without every node class having to duplicate every
string, so this module owns the translation tables and
:func:`enrich_spec` injects the mirrored fields at the single exit point
(:meth:`workflow_engine.node_base.ScientificNode.spec`):

===========================  ==================================================
injected field               content
===========================  ==================================================
``name_zh``                  Chinese display name of the node
``category_zh``              Chinese display name of the category
``description_en``           English description of the node
``parameters[].description_en``  English description of a parameter
``inputs/outputs[].description_en`` English description of a port
``parameters[].options_en``  English labels for ``(value, label)`` enum options
===========================  ==================================================

Rules
-----
* Keys of ``PARAM_DESCRIPTIONS_EN`` / ``PORT_DESCRIPTIONS_EN`` are the **Chinese
  source strings themselves**, so one entry covers every node that reuses it.
* A missing entry is never an error: the canonical string is mirrored verbatim
  and the GUI falls back to it (``enrich_spec`` is total by construction).
* This module is data-only on purpose: ``workflow_engine`` may import it (the
  dependency direction ``nodes/ -> workflow_engine/`` is untouched) and so may
  ``node_registry``, the SDK and the test-suite.
"""

