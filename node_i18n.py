# --------------------------------------------------------------------------- #
# Enum option labels (only the few that are not already technical English)     #
# --------------------------------------------------------------------------- #
OPTION_LABELS_EN: Dict[str, str] = {
    "中文": "Chinese",
    "English": "English",
}

OPTION_LABELS_ZH: Dict[str, str] = {
    "English": "英文",
    "Chinese": "中文",
}


def _localize_option(option: Any, table: Dict[str, str]) -> Any:
    """Mirror one enum option through ``table`` (identity when not a pair)."""
    if isinstance(option, (list, tuple)) and len(option) == 2:
        return [option[0], table.get(str(option[1]), option[1])]
    return option


def enrich_spec(spec: Dict[str, Any]) -> Dict[str, Any]:
    """Return ``spec`` with the mirrored ``*_zh`` / ``*_en`` display fields.

    Total by construction: every lookup falls back to the canonical value, so a
    missing translation degrades to the source string instead of raising.
    """
    out: Dict[str, Any] = dict(spec)
    node_type = out.get("type", "")

    out["name_zh"] = NODE_NAMES_ZH.get(node_type, out.get("name", ""))
    out["category_zh"] = CATEGORY_NAMES_ZH.get(
        out.get("category", ""), out.get("category", "")
    )
    out["description_en"] = NODE_DESCRIPTIONS_EN.get(
        node_type, out.get("description", "")
    )

    for key in ("inputs", "outputs"):
        ports: List[Dict[str, Any]] = []
        for port in out.get(key, []) or []:
            item = dict(port)
            item["description_en"] = PORT_DESCRIPTIONS_EN.get(
                item.get("description", ""), item.get("description", "")
            )
            ports.append(item)
        out[key] = ports

    params: List[Dict[str, Any]] = []
    for param in out.get("parameters", []) or []:
        item = dict(param)
        item["description_en"] = PARAM_DESCRIPTIONS_EN.get(
            item.get("description", ""), item.get("description", "")
        )
        item["options_en"] = [
            _localize_option(option, OPTION_LABELS_EN)
            for option in item.get("options", []) or []
        ]
        item["options_zh"] = [
            _localize_option(option, OPTION_LABELS_ZH)
            for option in item.get("options", []) or []
        ]
        params.append(item)
    out["parameters"] = params
    return out
